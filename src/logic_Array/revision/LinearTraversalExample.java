package logic_Array.revision;

public class LinearTraversalExample {

    public static void main(String[] args) {

        int[] arr = {5, 3, 8, 4, 2};

        System.out.println("Array elements:");

        for (int i = 0; i < arr.length; i++) {
            System.out.print(arr[i] + " ");
        }
    }
}
