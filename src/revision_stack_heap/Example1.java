package revision_stack_heap;

public class Example1 {

    static void calculate() {

        int a = 10;
        int b = 20;
        int sum = a + b;

        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("sum = " + sum);
    }

    public static void main(String[] args) {

        calculate();
    }
}
