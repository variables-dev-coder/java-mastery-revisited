package revision4;

public class ParameterMethods {

    static void greet(String name, int age) {

        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
    }

    public static void main(String[] args) {

        greet("Munna", 31);
        greet("Rahul", 25);
    }
}
